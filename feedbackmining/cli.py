"""Command-line entry point.

    python -m feedbackmining.cli run                # offline MockLLM, 5k synthetic notes
    python -m feedbackmining.cli run --fresh        # ignore existing checkpoints
    LLM_PROVIDER=anthropic python -m feedbackmining.cli run --n 200
    python -m feedbackmining.cli evaluate           # metrics + cost table (offline)

Outputs: reports/feature_gaps.md, reports/evaluation.md, docs/img/*.png,
checkpoints under runs/<provider>-n<N>-seed<S>/ (git-ignored).
"""
from __future__ import annotations

import argparse
import os
import shutil
import sys
import time
from collections import Counter, defaultdict
from pathlib import Path

from . import plots
from .cost import CostTracker
from .evaluate import evaluate
from .llm import get_client
from .pipeline import run_pipeline
from .schemas import Note
from .synthetic import generate, write_jsonl
from .taxonomy import FEATURE_BY_ID

ROOT = Path(__file__).resolve().parents[1]


def pct(v: float) -> str:
    return f"{v * 100:.1f}%"


def md_table(header: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def _quote(text: str, n: int = 90) -> str:
    text = " ".join(text.split()).replace("|", "/")
    return text if len(text) <= n else text[: n - 3] + "..."


def _pipeline(args) -> tuple[list[dict], dict, CostTracker, str, float]:
    provider = (args.provider or os.environ.get("LLM_PROVIDER", "mock")).lower()
    out_dir = ROOT / "runs" / f"{provider}-n{args.n}-seed{args.seed}"  # checkpoints are per corpus
    if args.fresh and out_dir.exists():
        shutil.rmtree(out_dir)
    gold = generate(n=args.n, seed=args.seed)
    write_jsonl(gold, out_dir / "notes.jsonl")
    notes = [Note(id=g["id"], text=g["text"]) for g in gold]
    tracker = CostTracker()
    t0 = time.time()
    results = run_pipeline(notes, get_client("stage1", provider), get_client("stage2", provider), out_dir,
                           tracker=tracker, max_input_tokens=args.batch_tokens)
    return gold, results, tracker, provider, time.time() - t0


def cmd_run(args) -> dict:
    gold, results, tracker, provider, elapsed = _pipeline(args)
    s1, s2 = results["stage1"], results["stage2"]
    st1, st2 = results["stats"]["stage1"], results["stats"]["stage2"]
    by_id = {g["id"]: g for g in gold}

    flagged = results["flagged_ids"]
    specific = [i for i in flagged if s2.get(i, {}).get("canonical_features")]
    counts = Counter(f for i in specific for f in s2[i]["canonical_features"])
    true_counts = Counter(f for g in gold for f in g["missing_features"])
    examples = defaultdict(list)
    for i in sorted(specific):
        for f in s2[i]["canonical_features"]:
            if len(examples[f]) < 2 and by_id[i]["text"] not in examples[f]:
                examples[f].append(by_id[i]["text"])
    strength = Counter(r["signal_strength"] for r in s1.values())

    img, rep = ROOT / "docs" / "img", ROOT / "reports"
    img.mkdir(parents=True, exist_ok=True)
    rep.mkdir(parents=True, exist_ok=True)
    ranked = counts.most_common()
    plots.top_features([(FEATURE_BY_ID[f].name, c, true_counts.get(f, 0)) for f, c in ranked],
                       img / "top_missing_features.png")
    plots.funnel([("all lost-deal notes", len(s1)), ("flagged: product gap", len(flagged)),
                  ("specific missing feature(s)", len(specific))], img / "funnel.png")

    rows = []
    for rank, (f, c) in enumerate(ranked, 1):
        q = "<br>".join(f"\"{_quote(t)}\"" for t in examples[f])
        rows.append([rank, FEATURE_BY_ID[f].name, f"`{f}`", c, pct(c / max(len(specific), 1)), q])
    cost_rows = [[r["stage"], r["provider"], r["model"], r["calls"], f"{r['input_tokens']:,}",
                  f"{r['output_tokens']:,}", f"${r['usd']:.4f}"] for r in tracker.rows()]
    lines = [
        "# Feature gaps behind lost deals",
        "",
        "> **Synthetic data.** Notes are generated by `feedbackmining/synthetic.py`; counts illustrate the"
        f" method only. Provider: `{provider}`" + (" (offline heuristic, no API calls)." if provider == "mock" else "."),
        "",
        "## Funnel",
        "",
        md_table(["step", "notes", "share of all"], [
            ["lost-deal notes", f"{len(s1):,}", "100%"],
            ["Stage 1 flagged a product gap (signal >= 1)", f"{len(flagged):,}", pct(len(flagged) / len(s1))],
            ["Stage 2 found >= 1 specific missing feature", f"{len(specific):,}", pct(len(specific) / len(s1))],
        ]),
        "",
        "Stage 1 signal strength distribution: " + ", ".join(f"{k}: {strength.get(k, 0):,}" for k in range(4)) + ".",
        "",
        "![funnel](../docs/img/funnel.png)",
        "",
        "## Ranked missing features",
        "",
        "Counts are deals (a note can name more than one feature). Share = share of deals with a specific feature.",
        "",
        md_table(["#", "feature", "id", "deals", "share", "example quotes"], rows),
        "",
        "![top missing features](../docs/img/top_missing_features.png)",
        "",
        "## Run statistics",
        "",
        f"- Stage 1: {st1.total:,} notes, {st1.skipped:,} resumed from checkpoint, {st1.processed:,} processed"
        f" in {st1.batches} batches, {st1.failed} failed.",
        f"- Stage 2: {st2.total:,} notes, {st2.skipped:,} resumed from checkpoint, {st2.processed:,} processed"
        f" in {st2.batches} batches, {st2.failed} failed.",
        f"- Wall time: {elapsed:.1f}s.",
        "",
        md_table(["stage", "provider", "model", "calls", "input tokens", "output tokens", "cost"], cost_rows)
        if cost_rows else "_All notes were resumed from checkpoints; no calls made in this run._",
        "",
        "Mock token counts are estimates (~3 characters per token); see `reports/evaluation.md` for"
        " projected costs per provider.",
        "",
    ]
    (rep / "feature_gaps.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"[run] provider={provider} notes={len(s1)} flagged={len(flagged)} specific={len(specific)} "
          f"features={len(counts)} time={elapsed:.1f}s")
    print("[run] top 5:", ", ".join(f"{f}={c}" for f, c in ranked[:5]))
    return dict(gold=gold, results=results)


def cmd_evaluate(args) -> None:
    if (args.provider or os.environ.get("LLM_PROVIDER", "mock")).lower() != "mock":
        print("[evaluate] note: evaluation re-measures token usage with the offline mock client")
    out = cmd_run(args)
    ev = evaluate(out["gold"], out["results"], get_client("stage2", "mock"))
    s1l, s1b = ev["stage1_llm"], ev["stage1_baseline"]
    e2e, cond = ev["stage2_e2e"], ev["stage2_on_true_positives"]

    def r3(d):
        return [f"{d['precision']:.3f}", f"{d['recall']:.3f}", f"{d['f1']:.3f}", d["tp"], d["fp"], d["fn"]]

    cost_rows = [[c["provider"], c["stage1_model"], c["stage2_model"], f"${c['stage1_usd']:.4f}",
                  f"${c['stage2_usd']:.4f}", f"**${c['two_stage_usd']:.4f}**", f"${c['single_stage_usd']:.4f}",
                  pct(c["saving"])] for c in ev["costs"]]
    tk = ev["tokens"]
    lines = [
        "# Evaluation (synthetic ground truth)",
        "",
        "> **Synthetic data, offline MockLLM.** The mock is a keyword/regex heuristic; a real LLM would be"
        " evaluated the same way by setting `LLM_PROVIDER`. Numbers show the evaluation harness, not a"
        " claim about any production system.",
        "",
        f"Deterministic split by hashed note id: {ev['n_train']:,} train / {ev['n_test']:,} test notes."
        " The TF-IDF baseline is trained on the train split; everything is scored on the test split.",
        "",
        "## Stage 1 - has_feature_issue",
        "",
        md_table(["classifier", "precision", "recall", "F1", "TP", "FP", "FN"], [
            ["MockLLM heuristic (zero-shot, no training data)"] + r3(s1l),
            ["TF-IDF + LogisticRegression (supervised)"] + r3(s1b),
        ]),
        "",
        f"Exact signal_strength (0-3) accuracy of the mock: {pct(ev['strength_acc'])}.",
        "",
        "## Stage 2 - missing_features (normalised to taxonomy)",
        "",
        md_table(["scope", "micro-precision", "micro-recall", "micro-F1", "TP", "FP", "FN"], [
            ["end-to-end (Stage 1 misses count as misses)"] + r3(e2e),
            [f"notes with a specific gap that Stage 1 flagged (n={ev['n_cond']})"] + r3(cond),
        ]),
        "",
        f"Ranking agreement on the full corpus: Spearman rho between extracted and true feature counts ="
        f" {ev['rank_corr']:.2f}; {ev['top10_overlap']}/10 of the true top-10 features are in the extracted top-10."
        " Product decisions use the *ranking*, which is more robust than per-note extraction.",
        "",
        "## Cost per 1,000 notes (ILLUSTRATIVE prices)",
        "",
        f"Token usage measured on this corpus ({ev['n_notes']:,} notes, {ev['n_flagged']:,} sent to Stage 2):"
        f" Stage 1 {tk['stage1'][0]:,} in / {tk['stage1'][1]:,} out; Stage 2 {tk['stage2'][0]:,} in /"
        f" {tk['stage2'][1]:,} out; single-stage alternative (strong model on every note)"
        f" {tk['single_stage'][0]:,} in / {tk['single_stage'][1]:,} out. Token counts are character-based"
        " estimates.",
        "",
        md_table(["provider", "stage-1 model", "stage-2 model", "stage 1", "stage 2", "two-stage total",
                  "single-stage", "saving"], cost_rows),
        "",
        "**Prices in `config/prices.json` are illustrative examples and go stale; check each provider's"
        " pricing page.** The point is the structure: the cheap model reads everything, the strong model"
        " reads only the flagged minority.",
        "",
    ]
    (ROOT / "reports" / "evaluation.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"[evaluate] stage1 F1 mock={s1l['f1']:.3f} baseline={s1b['f1']:.3f}; "
          f"stage2 micro-F1 e2e={e2e['f1']:.3f} on-flagged={cond['f1']:.3f}; rho={ev['rank_corr']:.2f}")
    for c in ev["costs"]:
        print(f"[evaluate] {c['provider']:<9} two-stage ${c['two_stage_usd']:.4f}/1k notes vs single-stage "
              f"${c['single_stage_usd']:.4f} (saving {c['saving']:.0%})")


def main(argv=None) -> None:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    p = argparse.ArgumentParser(description="Two-stage LLM mining of lost-deal notes (synthetic data)")
    p.add_argument("command", choices=["run", "evaluate"])
    p.add_argument("--n", type=int, default=5000, help="synthetic notes to generate")
    p.add_argument("--seed", type=int, default=7)
    p.add_argument("--provider", default=None, help="mock|anthropic|openai|gemini|deepseek (default: $LLM_PROVIDER or mock)")
    p.add_argument("--batch-tokens", type=int, default=2500, help="max estimated input tokens per batch")
    p.add_argument("--fresh", action="store_true", help="delete checkpoints for this provider first")
    args = p.parse_args(argv)
    {"run": cmd_run, "evaluate": cmd_evaluate}[args.command](args)


if __name__ == "__main__":
    main()
